export function hasTranslation(locale: Locale, source: string): boolean {
  if (locale === "zh-CN") return true;
  return Object.hasOwn(catalogs[locale], source);
}

export function translate(locale: Locale, source: string, values: TranslationValues = {}): string {
  if (locale === "zh-CN") return source.replace(/\{(\w+)\}/g, (match, key: string) => values[key] === undefined ? match : String(values[key]));
  const catalog = catalogs[locale];
  let template = catalog[source];
  if (template === undefined) {
    template = source;
    for (const [from, to] of Object.entries(catalog).filter(([key]) => key.length > 1 && source.includes(key)).sort(([a], [b]) => b.length - a.length)) {
      template = template.replaceAll(from, to);
    }
  }
  return template.replace(/\{(\w+)\}/g, (match, key: string) => values[key] === undefined ? match : String(values[key]));
}

